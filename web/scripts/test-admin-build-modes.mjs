import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { assertStaticNoAi } from "./assert-static-no-ai.mjs";
import { GENERATED_ROUTES, syncApiRoutes } from "./run-next-mode.mjs";

const scriptsRoot = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptsRoot, "..");
const runNext = path.join(scriptsRoot, "run-next-mode.mjs");
const syncAssets = path.join(scriptsRoot, "sync-typst-assets.mjs");
const timeout = 300_000;

function run(script, args = []) {
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: webRoot,
    env: process.env,
    stdio: "inherit",
    timeout,
  });
  if (result.error || result.signal || result.status !== 0) {
    throw new Error(`Admin build-mode command failed: ${path.basename(script)} ${args.join(" ")}`);
  }
}

async function assertServerRoutes() {
  for (const route of GENERATED_ROUTES) {
    const file = path.join(webRoot, route.file);
    if (!existsSync(file)) throw new Error(`Server route was not restored: ${route.file}`);
    const firstLine = readFileSync(file, "utf8").split(/\r?\n/u, 1)[0];
    if (!firstLine.includes("GENERATED BY run-next-mode.mjs")) {
      throw new Error(`Server route has no generated sentinel: ${route.file}`);
    }
  }
}

try {
  run(syncAssets);
  run(runNext, ["build", "server"]);
  run(runNext, ["build", "static"]);
  const scanned = await assertStaticNoAi(path.join(webRoot, "out"));
  console.log(`Static Admin boundary passed: ${scanned.filesScanned} files scanned.`);
  run(runNext, ["build", "server"]);
  await assertServerRoutes();
  console.log("Admin build-mode transition passed: server -> static -> server.");
} catch (error) {
  // Leave a failed developer/CI checkout in the normal server source shape.
  await syncApiRoutes("server").catch(() => {});
  console.error(error instanceof Error ? error.message : "Admin build-mode transition failed.");
  process.exitCode = 1;
}
