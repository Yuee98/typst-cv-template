// Dual-mode build wrapper — single source of truth for STATIC_EXPORT.
// (In a `sync-script && next build` chain env vars do not cross process
// boundaries, so the mode must be owned here, not by the shell.)
//
//   node scripts/run-next-mode.mjs <dev|build> <server|static> [next args...]
//
//   server → generates the API route files, spawns next with STATIC_EXPORT=false
//   static → removes the generated API route files, spawns next with STATIC_EXPORT=true
//
// Only the three route files listed in GENERATED_ROUTES are ever managed; the
// rest of src/app (and any hand-written file under src/app/api) is untouched.

import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const SENTINEL = "GENERATED BY run-next-mode.mjs — DO NOT EDIT";

const GENERATED_ROUTES = [
  { file: "src/app/api/polish/route.ts", exportSpec: "POST" },
  { file: "src/app/api/polish/quota/route.ts", exportSpec: "GET" },
  {
    file: "src/app/api/polish/availability/route.ts",
    exportSpec: "AVAILABILITY_GET as GET",
  },
];

function routeSource(exportSpec) {
  return [
    `// ${SENTINEL}`,
    `export const runtime = "nodejs";`,
    `export const maxDuration = 60;`,
    `export { ${exportSpec} } from "@/server/polish/handler";`,
    ``,
  ].join("\n");
}

async function hasSentinel(absPath) {
  const content = await readFile(absPath, "utf8");
  return content.split("\n", 1)[0].includes(SENTINEL);
}

async function syncApiRoutes(mode) {
  for (const route of GENERATED_ROUTES) {
    const absPath = join(webRoot, route.file);
    if (mode === "server") {
      if (existsSync(absPath) && !(await hasSentinel(absPath))) {
        throw new Error(
          `Refusing to overwrite hand-written file ${route.file} (missing generated sentinel).`,
        );
      }
      await mkdir(dirname(absPath), { recursive: true });
      await writeFile(absPath, routeSource(route.exportSpec));
    } else {
      if (!existsSync(absPath)) continue;
      if (!(await hasSentinel(absPath))) {
        throw new Error(
          `Refusing to delete hand-written file ${route.file} (missing generated sentinel).`,
        );
      }
      await rm(absPath);
    }
  }
  if (mode === "static") {
    // Prune now-empty directories left behind (availability/, quota/, polish/, api/).
    // rmdir fails on non-empty directories — that is the desired behaviour.
    const candidates = [
      "src/app/api/polish/availability",
      "src/app/api/polish/quota",
      "src/app/api/polish",
      "src/app/api",
    ];
    for (const dir of candidates) {
      await rmdir(join(webRoot, dir)).catch(() => {});
    }
  }
}

function checkFlagConsistency(mode) {
  // Static export must never ship an AI UI entry point (Invariant 9).
  if (mode === "static" && process.env.NEXT_PUBLIC_AI_POLISH_ENABLED === "true") {
    console.error(
      "Refusing to build: STATIC_EXPORT=true conflicts with NEXT_PUBLIC_AI_POLISH_ENABLED=true.\n" +
        "A static export has no API routes and must not expose the AI polish UI.",
    );
    process.exit(1);
  }
}

function runNext(subcommand, mode, extraArgs) {
  const require = createRequire(import.meta.url);
  const nextBin = join(dirname(require.resolve("next/package.json")), "dist", "bin", "next");
  const child = spawn(process.execPath, [nextBin, subcommand, ...extraArgs], {
    cwd: webRoot,
    stdio: "inherit",
    env: {
      ...process.env,
      STATIC_EXPORT: mode === "static" ? "true" : "false",
    },
  });
  child.on("error", (error) => {
    console.error(error);
    process.exit(1);
  });
  child.on("exit", (code, signal) => {
    if (signal) {
      process.kill(process.pid, signal);
      return;
    }
    process.exit(code ?? 1);
  });
}

const [subcommand, mode, ...extraArgs] = process.argv.slice(2);
if (!["dev", "build"].includes(subcommand) || !["server", "static"].includes(mode)) {
  console.error("Usage: node scripts/run-next-mode.mjs <dev|build> <server|static> [next args...]");
  process.exit(1);
}

checkFlagConsistency(mode);
await syncApiRoutes(mode);
runNext(subcommand, mode, extraArgs);
