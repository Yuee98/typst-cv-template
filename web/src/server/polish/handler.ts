const env = process.env;

function requireServerEnv(name: string): string {
  const value = env[name]?.trim();
  if (!value) {
    throw new Error(`Missing required server environment variable: ${name}`);
  }
  return value;
}

/** Structured metadata logger (no-store list enforced by PolishLogEvent). */
function logPolishEvent(event: PolishLogEvent): void {
  console.log(JSON.stringify(event));
}

function logPolishAvailabilityEvent(event: PolishAvailabilityLogEvent): void {
  console.log(JSON.stringify(event));
}

function logPolishLifecycleV2Event(event: PolishLifecycleV2LogEvent): void {
  console.log(JSON.stringify(event));
}

function logPolishPostV2Event(event: PolishPostV2HttpLogEvent): void {
  console.log(JSON.stringify(event));
}

interface PolishHandlerDeps {
  readonly quota: PolishQuotaRouteDeps;
  readonly availability: PolishAvailabilityDeps;
  readonly postV2: PolishPostV2Deps;
}

const FAKE_AVAILABILITY_DISABLED: PolishAvailabilityDbResult = Object.freeze({
  enabled: false,
  configGeneration: null,
  routingPolicyVersionId: null,
  profileVersionId: null,
  legalBundleVersion: null,
  runtimeContractId: null,
  runtimeContractSha256: null,
  displayDisclosureKey: null,
  termsAccepted: false,
});

const FAKE_AVAILABILITY_ENABLED: PolishAvailabilityDbResult = Object.freeze({
  enabled: true,
  configGeneration: FAKE_V2_EXPECTED_ROUTE.configGeneration,
  routingPolicyVersionId: FAKE_V2_POLICY_VERSION_ID,
  profileVersionId: FAKE_V2_EXPECTED_ROUTE.profileVersionId,
  legalBundleVersion: FAKE_V2_EXPECTED_ROUTE.legalBundleVersion,
  runtimeContractId: FAKE_V2_EXPECTED_ROUTE.runtimeContractId,
  runtimeContractSha256: FAKE_V2_EXPECTED_ROUTE.runtimeContractSha256,
  displayDisclosureKey: "deepseek-official-v1",
  termsAccepted: true,
});

function buildPolishHandlerDeps(): PolishHandlerDeps {
  // Apply the process-owned fake ceiling before constructing either backend.
  assertFakeLlmDeploymentAllowed(env);

  // CI smoke mode: fake auth/terms/quota behind an explicit second flag.
  if (env.POLISH_FAKE_BACKEND === "true") {
    if (env.POLISH_FAKE_LLM !== "true") {
      throw new Error(
        "POLISH_FAKE_BACKEND=true requires POLISH_FAKE_LLM=true: the fake backend exists " +
          "only for the CI smoke alongside the deterministic fake LLM. Refusing to start.",
      );
    }
    const provider = createFakePolishProvider();
    const providerV2 = createFakePolishInferenceProvider({
      route: {
        actualUpstreamEndpoint: resolveEndpoint("deepseek_official").url,
        actualModelId: DEEPSEEK_POLISH_MODEL,
      },
    });
    const fakeV2 = createFakePolishV2RouteDeps({ provider, providerV2, env });
    const quota: PolishQuotaRouteDeps = {
      verifyAccessToken: fakeV2.legacyV1.verifyAccessToken,
      getQuota: fakeV2.legacyV1.getQuota,
      aiPolishEnabled: fakeV2.legacyV1.aiPolishEnabled,
      logger: logPolishEvent,
    };
    return {
      quota,
      availability: {
        verifyAccessToken: fakeV2.legacyV1.verifyAccessToken,
        readAvailability: async () =>
          env.AI_POLISH_ENABLED === "true"
            ? FAKE_AVAILABILITY_ENABLED
            : FAKE_AVAILABILITY_DISABLED,
        logger: logPolishAvailabilityEvent,
      },
      postV2: {
        verifyAccessToken: fakeV2.legacyV1.verifyAccessToken,
        executeLifecycle: bindPolishLifecycleV2({
          ...fakeV2,
          logger: logPolishLifecycleV2Event,
        }),
        logger: logPolishPostV2Event,
      },
    };
  }

  // Real backend: auth/accounting against Supabase. Both factories throw on
  // missing env (refuse-to-start).
  const authDeps = createPolishAuthDeps();
  const adminClient = createServerAdminClient();
  // Required even with the fake LLM: all provider subjects/route tags are
  // server-keyed so raw identity/correlation values cannot cross boundaries.
  const hmacSecret = requireServerEnv("AI_USER_ID_HMAC_SECRET");
  const fakeLlm = env.POLISH_FAKE_LLM === "true";
  const fakeProviderV2 = fakeLlm
    ? createFakePolishInferenceProvider({
        route: {
          actualUpstreamEndpoint: resolveEndpoint("deepseek_official").url,
          actualModelId: DEEPSEEK_POLISH_MODEL,
        },
      })
    : undefined;
  const routesV2: PolishRouteDepsV2 = {
    reserve: (params) => reservePolishRequestV2(adminClient, params),
    getExecutionSnapshot: (params) => getPolishExecutionSnapshotV1(adminClient, params),
    startAttempt: (params) => startPolishProviderAttemptV2(adminClient, params),
    completeAttempt: (params) => completePolishProviderAttemptV2(adminClient, params),
    finalize: (params) => finalizePolishRequestV2(adminClient, params),
    // RT-009A replaces the production-empty resolver with the exact reviewed
    // runtime evidence registry. Until then a mistakenly activated DB route
    // releases before attempt admission/network. The fake-only seam may
    // accept its synthetic runtime because both provider paths are inert.
    runtimeTargetResolver: fakeLlm
      ? () => true
      : EMPTY_RUNTIME_TARGET_RESOLVER_V1,
    resolveProvider:
      fakeProviderV2 === undefined
        ? createCodeOwnedPolishAdapterResolverV2({ env })
        : () => fakeProviderV2,
    providerSubjectSecret: hmacSecret,
    routeObservationSecret: hmacSecret,
    logger: logPolishLifecycleV2Event,
  };

  return {
    quota: {
      verifyAccessToken: authDeps.verifyAccessToken,
      getQuota: (userId) => getPolishQuota(adminClient, userId),
      // Availability/POST use the DB kill switch. Quota remains readable while
      // the feature is dark so a stale build-time env flag cannot own runtime.
      aiPolishEnabled: true,
      logger: logPolishEvent,
    },
    availability: {
      verifyAccessToken: authDeps.verifyAccessToken,
      readAvailability: (userId) => readPolishAvailabilityV1(adminClient, userId),
      logger: logPolishAvailabilityEvent,
    },
    postV2: {
      verifyAccessToken: authDeps.verifyAccessToken,
      executeLifecycle: bindPolishLifecycleV2(routesV2),
      logger: logPolishPostV2Event,
    },
  };
}

// Module-scope resolution IS the refuse-to-start mechanism: any
// misconfiguration above throws during import, before a request is served.
const deps = buildPolishHandlerDeps();

export const POST = createPolishPostV2Handler(deps.postV2);
export const GET = (request: Request) => handleQuotaGet(request, deps.quota);
export const AVAILABILITY_GET = createPolishAvailabilityHandler(deps.availability);
